// The two legal pages in the other six languages.
//
// Stored as a flat run of strings rather than as a second copy of the document
// tree, and rebuilt against the English structure below. The structure — which
// section has a bulleted list, which line is bold — is the same document in
// every language and is not a translator's decision; only the words change. A
// tree per language would have been six chances to drop a bullet.
//
// The order is exactly the order the strings appear on the page: the title,
// the dated lines under it, then every heading, paragraph, label and bullet in
// turn. `check()` below fails the build if a run is the wrong length, which is
// the failure this shape can actually have.

function rebuild(source: Policy, words: string[]): Policy {
  let at = 0;
  const next = () => {
    const word = words[at++];
    if (word === undefined) {
      throw new Error(`policyPacks: ran out of strings at ${at - 1}`);
    }
    return word;
  };

  const block = (b: PolicyBlock): PolicyBlock => {
    if (b.kind === "p" || b.kind === "strong") return { ...b, text: next() };
    if (b.kind === "kv") {
      return {
        kind: "kv",
        items: b.items.map(() => ({ label: next(), text: next() })),
      };
    }
    return {
      kind: "list",
      ...(b.heading ? { heading: next() } : {}),
      ...(b.lead ? { lead: next() } : {}),
      items: b.items.map(() => next()),
    };
  };

  const title = next();
  const meta = source.meta.map(() => next());
  const intro = source.intro.map(block);
  const sections = source.sections.map((section) => ({
    heading: next(),
    blocks: section.blocks.map(block),
  }));

  if (at !== words.length) {
    throw new Error(`policyPacks: ${words.length - at} strings left over`);
  }
  return { title, meta, intro, sections };
}

